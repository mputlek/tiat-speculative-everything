#!/usr/bin/env node
// Runs at Netlify build time (see netlify.toml). Writes shared/config.js
// from the ABLY_API_KEY env var set in Netlify's site settings, so the real
// key lives only in Netlify/local shell env — never in git.
//
// Local dev without this script: just copy shared/config.template.js to
// shared/config.js by hand and fill in your key.

const fs = require('fs');
const path = require('path');

const apiKey = process.env.ABLY_API_KEY;
const channelName = process.env.FUNGUY_CHANNEL_NAME || 'funguy-healing';
const healthIncrement = process.env.FUNGUY_HEALTH_INCREMENT || '2';
const healthMax = process.env.FUNGUY_HEALTH_MAX || '100';

if (!apiKey) {
  console.error(
    '\n[generate-config] Missing ABLY_API_KEY environment variable.\n' +
    'Set it in Netlify: Site settings > Environment variables > ABLY_API_KEY.\n' +
    'For local dev, either export ABLY_API_KEY before running this script,\n' +
    'or just copy shared/config.template.js to shared/config.js by hand.\n'
  );
  process.exit(1);
}

const out = `// AUTO-GENERATED by scripts/generate-config.js — do not edit by hand.
// This file is gitignored; it's rebuilt from env vars on every deploy.
window.FUNGUY_CONFIG = {
  ABLY_API_KEY: ${JSON.stringify(apiKey)},
  CHANNEL_NAME: ${JSON.stringify(channelName)},
  HEALTH_INCREMENT: ${Number(healthIncrement)},
  HEALTH_MAX: ${Number(healthMax)},
};
`;

const outPath = path.join(__dirname, '..', 'shared', 'config.js');
fs.writeFileSync(outPath, out);
console.log(`[generate-config] Wrote ${outPath}`);
